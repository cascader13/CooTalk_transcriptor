import argparse
import os
import uuid

import grpc

from app.generated import transcription_pb2 as pb
from app.generated import transcription_pb2_grpc as pb_grpc


def main():
    parser = argparse.ArgumentParser(description="Submit an audio transcription task")
    parser.add_argument("storage_key", help="Audio object's storage key")
    parser.add_argument("--task-id", default=None, help="Task ID (a UUID is generated by default)")
    parser.add_argument("--server", default=os.getenv("GRPC_TARGET", "localhost:50051"),
                        help="gRPC server address (default: GRPC_TARGET or localhost:50051)")
    args = parser.parse_args()

    with grpc.insecure_channel(args.server) as channel:
        stub = pb_grpc.TranscriptionServiceStub(channel)
        task_id = args.task_id or str(uuid.uuid4())
        stub.AddTranscriptionTask(pb.TranscriptionTask(taskId=task_id, storageKey=args.storage_key))
        print(f"Accepted transcription task {task_id}")


if __name__ == "__main__":
    main()
